(function applyAuthI18n() {
  let lang = 'en';
  try { const s = localStorage.getItem('scalpel_lang'); if (s && AUTH_I18N[s]) lang = s; } catch (e) {}
  const dict = AUTH_I18N[lang] || AUTH_I18N.en;
  const t = (k) => (dict[k] !== undefined ? dict[k] : (AUTH_I18N.en[k] || k));
  // El botón de registro necesita traducir 'Creando tu cuenta…' en el
  // momento del clic, fuera de este IIFE.
  window.AuthI18n = { t: t };

  document.documentElement.lang = lang;
  // Default is LIGHT; switch to dark only if the user previously saved dark.
  try { if (localStorage.getItem('scalpel_theme') !== 'dark') document.body.classList.add('light'); }
  catch (e) { document.body.classList.add('light'); }

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    let txt = t(el.getAttribute('data-i18n'));
    // Optional {email} interpolation (used on the verification screen).
    if (txt.indexOf('{email}') !== -1) {
      txt = txt.replace('{email}', el.getAttribute('data-email') || 'your email');
    }
    el.textContent = txt;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
  // Strings that legitimately contain markup (e.g. the Terms link) opt in here.
  // Values come only from the translation table below — never from user input.
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });

  // ── fecha de nacimiento (solo /register) ──
  // El mes va por NOMBRE para que no exista ningún formato dd/mm vs mm/dd que
  // confundir. Los nombres salen de Intl según el idioma del SITIO (no del
  // sistema); el inglés server-rendered queda de fallback sin JS.
  const dob = document.getElementById('dob-row');
  if (dob) {
    if (lang !== 'en') {
      dob.classList.add('dmy');            // día antes que mes fuera de EN
      const sm = document.getElementById('birth_m');
      for (const op of sm.options) {
        if (!op.value) continue;
        let n = new Date(2000, op.value - 1, 1)
                  .toLocaleDateString(lang, { month: 'long' });
        op.textContent = n.charAt(0).toUpperCase() + n.slice(1);
      }
    }
    // El HTML llega hasta 2008 (18 años antes de 2026). A partir de 2027 van
    // faltando años válidos: se añaden aquí y el server sigue juzgando 18+.
    const sy = document.getElementById('birth_y');
    const tope = new Date().getFullYear() - 18;
    for (let y = 2009; y <= tope; y++) {
      const op = document.createElement('option');
      op.value = y; op.textContent = y;
      sy.insertBefore(op, sy.options[1]);  // el más nuevo arriba, como el resto
    }
  }
})();
