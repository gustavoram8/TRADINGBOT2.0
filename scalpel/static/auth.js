(function applyAuthI18n() {
  let lang = 'en';
  try { const s = localStorage.getItem('scalpel_lang'); if (s && AUTH_I18N[s]) lang = s; } catch (e) {}
  const dict = AUTH_I18N[lang] || AUTH_I18N.en;
  const t = (k) => (dict[k] !== undefined ? dict[k] : (AUTH_I18N.en[k] || k));

  document.documentElement.lang = lang;
  try { if (localStorage.getItem('scalpel_theme') === 'light') document.body.classList.add('light'); }
  catch (e) {}

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    let txt = t(el.getAttribute('data-i18n'));
    // Optional {email} interpolation (used on the verification screen).
    if (txt.indexOf('{email}') !== -1) {
      txt = txt.replace('{email}', el.getAttribute('data-email') || 'your email');
    }
    el.textContent = txt;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
  });
})();
