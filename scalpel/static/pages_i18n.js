  function getLang() {
    try { var s = localStorage.getItem('scalpel_lang'); if (s && T[s]) return s; } catch (e) {}
    return 'en';
  }

  // Resolve a key for the active lang, falling back to English so partially
  // translated languages (and the FR/PT stubs) never show a blank.
  function str(lang, key) {
    var d = T[lang] || {};
    if (d[key] != null) return d[key];
    return (T.en[key] != null) ? T.en[key] : null;
  }

  function apply(lang) {
    if (!T[lang]) lang = 'en';
    document.documentElement.setAttribute('lang', lang);

    var titleEl = document.querySelector('[data-i18n-title]');
    if (titleEl) {
      var tk = titleEl.getAttribute('data-i18n-title');
      var tv = str(lang, tk);
      if (tv != null) document.title = tv;
    }

    // Sustitución de variables en el propio HTML: data-i18n-vars='{"dias":20}'
    // rellena los {dias} de la traducción. Hace falta cuando el número lo sabe
    // el SERVIDOR (días que quedan, importes) y el texto que lo rodea cambia de
    // idioma: sin esto habría que partir la frase en trozos, y en francés o en
    // portugués los trozos no van en el mismo orden.
    function conVars(el, s) {
      if (s == null) return s;
      var crudo = el.getAttribute('data-i18n-vars');
      if (!crudo) return s;
      try {
        var vars = JSON.parse(crudo);
        Object.keys(vars).forEach(function (k) {
          s = s.split('{' + k + '}').join(vars[k]);
        });
      } catch (e) {}
      return s;
    }

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = conVars(el, str(lang, el.getAttribute('data-i18n')));
      if (v != null) el.textContent = v;
    });
    // Hover tooltips. NOT data-i18n-title: that one is reserved above for the
    // document <title>, and reusing it here would fight over the same key.
    document.querySelectorAll('[data-i18n-tip]').forEach(function (el) {
      var v = str(lang, el.getAttribute('data-i18n-tip'));
      if (v != null) el.setAttribute('title', v);
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var v = conVars(el, str(lang, el.getAttribute('data-i18n-html')));
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var v = str(lang, el.getAttribute('data-i18n-ph'));
      if (v != null) el.setAttribute('placeholder', v);
    });
    document.querySelectorAll('.lang-switch [data-lang]').forEach(function (b) {
      b.classList.toggle('active', b.getAttribute('data-lang') === lang);
    });

    try { localStorage.setItem('scalpel_lang', lang); } catch (e) {}
    try { document.cookie = 'scalpel_lang=' + lang + ';path=/;max-age=31536000;samesite=Lax'; } catch (e) {}
  }

  // Expose a tiny helper so inline page scripts (e.g. checkout promo feedback,
  // settings cancel-confirm) can reuse the same dictionary.
  window.PagesI18n = {
    lang: getLang,
    t: function (key, vars) {
      var s = str(getLang(), key);
      if (s == null) return key;
      if (vars) {
        Object.keys(vars).forEach(function (k) {
          s = s.replace('{' + k + '}', vars[k]);
        });
      }
      return s;
    }
  };

  function init() {
    apply(getLang());
    document.querySelectorAll('.lang-switch [data-lang]').forEach(function (b) {
      b.addEventListener('click', function () { apply(b.getAttribute('data-lang')); });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
